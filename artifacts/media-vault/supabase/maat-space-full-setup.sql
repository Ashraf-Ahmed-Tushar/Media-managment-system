create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Student',
  email text not null unique,
  role text not null default 'user' check (role in ('user', 'admin')),
  semester text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  kind text not null default 'all' check (kind in ('all', 'book', 'video', 'pyq')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text,
  description text,
  category_id bigint references public.categories(id) on delete set null,
  cover_url text,
  pdf_url text,
  preview_pages integer check (preview_pages is null or preview_pages >= 0),
  total_pages integer check (total_pages is null or total_pages > 0),
  rating numeric(2, 1) check (rating is null or (rating >= 0 and rating <= 5)),
  language text,
  publish_year integer,
  tags text[] not null default '{}',
  status text not null default 'published' check (status in ('published', 'draft')),
  is_restricted boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (title, author)
);

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  type text not null default 'lecture',
  category_id bigint references public.categories(id) on delete set null,
  thumbnail_url text,
  tags text[] not null default '{}',
  source_type text not null default 'external'
    check (source_type in ('youtube', 'drive', 'external')),
  source_url text not null,
  access_level text not null default 'free'
    check (access_level in ('free', 'restricted')),
  status text not null default 'published' check (status in ('published', 'draft')),
  is_restricted boolean not null default false,
  view_count bigint not null default 0 check (view_count >= 0),
  release_date date,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pyq_papers (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category_id bigint references public.categories(id) on delete set null,
  semester text,
  subject_name text,
  course_code text,
  exam_type text,
  batch_info text,
  file_urls text[] not null default '{}',
  tags text[] not null default '{}',
  status text not null default 'published' check (status in ('published', 'draft')),
  is_restricted boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (course_code, semester, exam_type, batch_info)
);

create table if not exists public.playlists (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  kind text not null check (kind in ('book', 'video')),
  thumbnail_url text,
  created_by uuid not null references public.profiles(id) on delete cascade,
  is_public boolean not null default false,
  category_id bigint references public.categories(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.playlist_items (
  id bigint generated by default as identity primary key,
  playlist_id bigint not null references public.playlists(id) on delete cascade,
  book_id bigint references public.books(id) on delete cascade,
  video_id bigint references public.videos(id) on delete cascade,
  position integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  check ((book_id is not null and video_id is null) or (book_id is null and video_id is not null)),
  unique (playlist_id, book_id),
  unique (playlist_id, video_id)
);

-- Mirrors the proposal's generic Favorites entity. The content_type/content_id
-- pair points to books, videos, or pyq_papers and is validated by the app.
create table if not exists public.favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content_type text not null check (content_type in ('book', 'video', 'pyq')),
  content_id bigint not null check (content_id > 0),
  created_at timestamptz not null default now(),
  unique (user_id, content_type, content_id)
);

create table if not exists public.watch_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  video_id bigint not null references public.videos(id) on delete cascade,
  progress_seconds integer not null default 0 check (progress_seconds >= 0),
  last_watched_at timestamptz not null default now(),
  unique (user_id, video_id)
);

create table if not exists public.book_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  last_page integer not null default 0 check (last_page >= 0),
  last_read_at timestamptz not null default now(),
  unique (user_id, book_id)
);

create table if not exists public.pyq_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  pyq_id bigint not null references public.pyq_papers(id) on delete cascade,
  last_opened_at timestamptz not null default now(),
  unique (user_id, pyq_id)
);

create table if not exists public.search_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  query_text text not null check (length(trim(query_text)) > 0),
  content_type text not null default 'all'
    check (content_type in ('all', 'book', 'video', 'pyq')),
  created_at timestamptz not null default now()
);

